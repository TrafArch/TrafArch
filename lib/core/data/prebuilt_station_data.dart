/// 将紧凑快照行展开为读卡识途标准 CSV（首列补城市代码）。
String expandSnapshotRows(String cityCode, String rows) {
  final buffer = StringBuffer('City,Code,Type,Line,Station\n');
  var type = '';
  var line = '';
  for (final raw in rows.split('\n')) {
    final row = raw.trim();
    if (row.isEmpty) continue;
    String code;
    String station;
    if (row.startsWith('*')) {
      final parts = row.substring(1).split(',');
      code = parts.isNotEmpty ? parts[0].trim() : '';
      type = parts.length > 1 ? parts[1].trim() : '';
      line = parts.length > 2 ? parts[2].trim() : '';
      station = parts.length > 3 ? parts.sublist(3).join(',').trim() : '';
    } else {
      final index = row.indexOf(',');
      code = index < 0 ? row : row.substring(0, index).trim();
      station = index < 0 ? '' : row.substring(index + 1).trim();
    }
    if (code.isEmpty) continue;
    buffer.writeln('$cityCode,$code,$type,$line,$station');
  }
  return buffer.toString();
}

