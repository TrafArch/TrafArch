def make_documents():
    manifest = json.loads((ASSETS / "reference_manifest.json").read_bytes())
    files = {}
    index = [
        "# transit 交通卡资料目录", "", GENERATED, "",
        "本目录供 CNB 知识库检索。来源为 TrafArch 随应用发布的两份公开参考库。"
        "城市表收录库内的站点、线路和部分运营商或终端兼容记录；地理覆盖以各包的实际记录为准。",
        "", "## 如何判断命中", "",
        "- 先分清 TU（交通联合）与 CU（城市一卡通），再用地区码和原始字段缩小范围。"
        "同一城市在两库使用的编码可能不同，例如上海在 TU 为 2900，在 CU 为 2000。",
        "- 原码、前缀、线路码、站点码都按文本读取，保留前导零。NULL 表示库内空值，∅ 表示空字符串。"
        r"原始回车和换行显示为 \r 和 \n。",
        "- 同一原码可能对应多条记录。结合来源字段列出候选，保留别名和歧义。",
        "- TU 的 supplemental_inferred 和 inferred 标识推算记录；compatibility_copy 标识兼容副本；"
        "local_terminal_or_route 是地方终端或线路命名空间。high 等置信度来自参考库，实体卡验收另有证据。",
        "- CU 历史公交线路在 bus_routes 中按终端后缀检索，结合交易类型、有效期、站名是否缺失和公交查询开关判定。"
        "cu_terminal_mappings 保存原始终端映射，cu_terminal_rules 给出按城市适用的字段与优先级，"
        "terminal_index 用地区码与 station_id 关联城市表。",
        "", "## 来源与更新", "",
        "随已发布的参考包更新本目录。在仓库根目录执行以下命令生成并核对文档。", "",
        "```sh", "python -X utf8 .cnb/transit_knowledge.py",
        "python -X utf8 .cnb/transit_knowledge.py --check", "```", "",
        "生成器只读打开 SQLite，先与 assets/data/reference_manifest.json 的发布包 SHA256 比对。"
        "CNB 的 knowledge:update 按 Git 提交差异索引文本，生成的 Markdown 需与对应的发布包一起提交。",
        "",
        "公开线路与站点数据的来源包括读卡识途作者 domosekai、HaoTian22 和其他贡献者。"
        "两份上游数据集采用 CC BY 4.0。TrafArch 按城市整理参考库，本目录从发布包选取公开字段，"
        "按协议、城市和来源重新排列并转为 Markdown。"
        "[项目致谢](../../README.md#致谢) · [读卡识途公开数据](https://github.com/domosekai/tripreader-data) · "
        "[HaoTian22 社区数据](https://github.com/HaoTian22/tripreader-data) · "
        "[CC BY 4.0](https://creativecommons.org/licenses/by/4.0/)",
    ]
    index.extend(technology_notes())
    for protocol in ("TU", "CU"):
        filename = f"TrafArch_Database_{protocol}.sqlite"
        path = ASSETS / filename
        package = manifest["packages"][protocol]
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if package["file"] != filename or digest != package["sha256"]:
            raise ValueError(f"{filename} does not match reference_manifest.json")
        index.extend(["", f"## {protocol} 参考库", "", f"来源 `{filename}`，SHA256 为 `{digest}`。", ""])
        directory = protocol.lower()
        with closing(sqlite3.connect(path.as_uri() + "?mode=ro&immutable=1", uri=True)) as db:
            for table, body in dictionary_documents(db, protocol):
                relative = f"{directory}/{table}.md"
                files[relative] = body
                index.append(f"- [{body.splitlines()[0][2:]}]({relative})")
            index.extend(["", "| 城市 | 地区码 | 城市表 | 记录数 |", "|---|---|---|---|"])
            for region_id, name, code, table in db.execute(
                "SELECT region_id, region_name, region_code, table_name FROM regions ORDER BY region_id"
            ):
                relative = f"{directory}/region-{region_id}.md"
                files[relative] = city_document(db, protocol, name, code, table)
                count = package["tables"][table]
                index.append(f"| [{cell(name)}]({relative}) | {cell(code)} | `{table}` | {count} |")
    files["README.md"] = "\n".join(index) + "\n"
    return files


def synchronize(check):
    expected = make_documents()
    extra = sorted(path for path in OUTPUT.rglob("*.md") if path.relative_to(OUTPUT).as_posix() not in expected)
    for path in extra:
        if GENERATED not in path.read_text("utf-8").splitlines()[:3]:
            raise ValueError(f"Unmanaged document in the index directory: {path}")
    changed = []
    for name, contents in expected.items():
        path = OUTPUT / name
        # Git can check out text files with CRLF on Windows.
        if not path.exists() or path.read_text("utf-8") != contents:
            changed.append(name)
    if check and (changed or extra):
        for name in changed:
            print(f"Missing or outdated: {name}", file=sys.stderr)
        for path in extra:
            print(f"Obsolete: {path}", file=sys.stderr)
        return 1
    if not check:
        for name in changed:
            path = OUTPUT / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected[name].encode("utf-8"))
        for path in extra:
            path.unlink()
    print(f"{len(expected)} transit knowledge documents verified against TU and CU.")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report differences without writing files")
    try:
        sys.exit(synchronize(parser.parse_args().check))
    except (OSError, ValueError, sqlite3.Error) as error:
        sys.exit(str(error))
