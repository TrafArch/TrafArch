ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets" / "data"
OUTPUT = ROOT / "docs" / "transit-data"
GENERATED = "<!-- Generated by .cnb/transit_knowledge.py -->"


def cell(value):
    if value is None:
        return "NULL"
    if value == "":
        return "∅"
    return str(value).replace("\\", "\\\\").replace("|", "\\|").replace("\r", r"\r").replace("\n", r"\n")


def table_document(title, source, headings, rows):
    """Repeat headings with the title for retrieval within long documents."""
    lines = [f"# {title}", "", GENERATED, "", source]
    for number, row in enumerate(rows):
        if number % 24 == 0:
            lines.extend([
                "", f"## {title} · 第 {number + 1} 条起", "",
                "| " + " | ".join(headings) + " |",
                "|" + "---|" * len(headings),
            ])
        lines.append("| " + " | ".join(cell(value) for value in row) + " |")
    return "\n".join(lines) + "\n"


def city_document(db, protocol, name, code, table):
    table_sql = '"' + table.replace('"', '""') + '"'
    fields = """s.source_key, s.line_name, s.station_name, s.system_name,
                s.transport_type, s.source_field, s.confidence"""
    headings = ["归属", "原码 source_key", "线路", "站名", "系统", "交通类型", "来源字段", "置信度"]
    title = f"{protocol} {name} {cell(code)}"
    if protocol == "TU":
        headings.extend(["记录归类", "查询命名空间", "记录类型", "原生归属", "station_id"])
        query = f"""SELECT ?, {fields}, p.copy_role, p.lookup_key_namespace,
                           p.record_kind, p.native_namespace, s.station_id
                    FROM {table_sql} AS s LEFT JOIN record_provenance AS p
                      ON p.table_name = ? AND p.station_id = s.station_id
                    ORDER BY s.source_key, s.station_id"""
        rows = db.execute(query, (title, table))
    else:
        headings.extend(["线路码", "站点码", "默认项 is_default", "station_id"])
        query = f"""SELECT ?, {fields}, s.line_code, s.station_code, s.is_default, s.station_id
                    FROM {table_sql} AS s ORDER BY s.source_key, s.station_id"""
        rows = db.execute(query, (title,))
    source = f"资料源为 `TrafArch_Database_{protocol}.sqlite` 的 `{table}` 城市表。"
    return table_document(title, source, headings, rows)


def dictionary_documents(db, protocol):
    # Each entry describes source columns in their stored form. Rows from
    # different lookup namespaces stay in separate documents.
    if protocol == "TU":
        specs = [
            ("card_prefixes", "卡号前缀", ["前缀", "机构码", "地区码", "卡名", "城市", "省份", "币种"],
             "prefix, issuer, region_code, card_name, city_name, province, currency"),
            ("issuer_city_codes", "发卡机构", ["机构码", "地区码", "城市", "卡名", "前缀"],
             "issuer, region_code, city_name, card_name, prefix"),
            ("protocol_region_codes", "协议地区码", ["来源字段", "原码", "库内名称", "有效标记", "来源序号"],
             "field_id, key_text, text_0, effective, entry_index"),
        ]
    else:
        specs = [
            ("cu_card_names", "卡种名称", ["机构码", "卡名", "来源字段"],
             "issuer_code, name_zh_cn, source_field"),
            ("cu_name_overrides", "条件卡名", ["机构码", "卡名", "规则", "须匹配卡名表", "最短字节数", "字节索引", "高半字节"],
             "issuer_code, name_zh_cn, rule_id, requires_map_match, min_raw_length, byte_index, high_nibble"),
            ("region_codes", "地区码", ["地区码", "库内名称"], "region_code, region_name"),
            ("routes", "线路码", ["地区码", "原线路键", "线路码", "线路序号", "线路名", "查询命名空间", "来源字段"],
             "region_code, line_key, line_code, line_number, line_name, lookup_namespace, source_field"),
            ("cu_terminal_rules", "终端字段查询规则", ["CU 地区码", "TU 查询前缀", "来源字段", "查询优先级"],
             "cu_region_code, tu_lookup_prefix, field_id, lookup_priority"),
            ("unresolved_terminals", "未解析终端", ["地区码", "终端原码", "库内原因"],
             "region_code, terminal_id, reason"),
        ]
    for table, label, headings, columns in specs:
        title = f"{protocol} {label}"
        rows = db.execute(f"SELECT {columns} FROM {table} ORDER BY {columns}")
        source = f"资料源为 `TrafArch_Database_{protocol}.sqlite` 的 `{table}` 表。"
        yield table, table_document(title, source, headings, rows)
    if protocol == "CU":
        yield from cu_terminal_documents(db)


def cu_terminal_documents(db):
    cities = dict(db.execute("SELECT region_code, region_name FROM regions"))
    rules = {}
    for field, code in db.execute("SELECT DISTINCT field_id, cu_region_code FROM cu_terminal_rules ORDER BY 1, 2"):
        rules.setdefault(field, []).append(f"{cities.get(code, '')} {code}".strip())
    specs = [
        ("bus_routes", "region_code", "历史公交线路",
         ["地区码", "终端后缀", "公交线路", "交易类型条件", "有效期上界 Unix 毫秒（不含）",
          "须无站名", "须启用公交查询", "来源字段", "来源序号"],
         "region_code, terminal_suffix, route_number, required_transaction_type, valid_before_unix_ms, "
         "requires_station_missing, requires_bus_lookup_enabled, source_field, source_entry_index",
         "查询时须同时满足同一行的交易类型、有效期、站名缺失和公交查询开关条件。"),
        ("cu_terminal_mappings", "field_id", "原始终端映射",
         ["来源字段", "原终端码", "原映射值（JSON）", "有效标记", "来源序号"],
         "field_id, key_text, value_json, effective, entry_index",
         "映射值是原字段的中间查询值；城市与字段优先级见 cu_terminal_rules。"),
        ("terminal_index", "region_code", "终端到城市表记录",
         ["地区码", "原查询键", "匹配方式", "交易类型条件", "优先级", "城市表 station_id"],
         "region_code, match_key, match_mode, required_transaction_type, priority, station_id",
         "用地区码和 station_id 回查该城市表里的线路、站名及来源。exact 为精确，prefix 为前缀，交易类型 -1 表示不限。"),
    ]
    for table, group_column, label, headings, columns, note in specs:
        for (group,) in db.execute(f"SELECT DISTINCT {group_column} FROM {table} ORDER BY 1"):
            if not re.fullmatch(r"[A-Za-z0-9_.-]+", group):
                raise ValueError(f"Unsupported {table} group in filename: {group!r}")
            if group_column == "field_id":
                scope = f"{group}（{'、'.join(rules.get(group, [])) or '库内未列关联城市'}）"
            else:
                scope = f"{cities.get(group, '')} {group}".strip()
            rows = db.execute(f"SELECT {columns} FROM {table} WHERE {group_column}=? ORDER BY {columns}", (group,))
            page = 1
            while chunk := list(islice(rows, 1000)):
                title = f"CU {scope} {label}（{page}）"
                source = f"资料源为 `TrafArch_Database_CU.sqlite` 的 `{table}` 表。{note}"
                yield f"{table}-{group}-{page:02}", table_document(title, source, headings, chunk)
                page += 1


