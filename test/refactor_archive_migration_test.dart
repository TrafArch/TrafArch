File _legacyFile(
  int version, {
  int? physicalVersion,
  String payload = _legacyPayload,
  void Function(sqlite.Database)? arrange,
}) {
  final directory = Directory.systemTemp.createTempSync(
    'trafarch-archive-regression-',
  );
  addTearDown(() => directory.deleteSync(recursive: true));
  final file = File('${directory.path}/archive.sqlite');
  final sql = sqlite.sqlite3.open(file.path);
  final physical = physicalVersion ?? version;
  try {
    sql.execute('''CREATE TABLE saved_cards (
      id TEXT NOT NULL PRIMARY KEY,
      card_fingerprint TEXT NOT NULL UNIQUE,
      card_type TEXT NOT NULL,
      official_name TEXT NULL,
      custom_name TEXT NULL,
      issuer_name TEXT NULL,
      city_name TEXT NULL,
      identification_source TEXT NOT NULL DEFAULT 'unknown',
      identification_confidence REAL NULL,
      card_image_path TEXT NULL,
      last_read_at INTEGER NULL,
      created_at INTEGER NOT NULL,
      updated_at INTEGER NOT NULL
    )''');
    if (physical < 3 || physical >= 6) {
      sql.execute(
        'ALTER TABLE saved_cards ADD COLUMN card_number_masked TEXT NULL',
      );
    }
    if (physical >= 3) {
      sql.execute('ALTER TABLE saved_cards ADD COLUMN card_number TEXT NULL');
    }
    if (physical >= 2) {
      sql.execute(
        'ALTER TABLE saved_cards ADD COLUMN balance_fen INTEGER NULL',
      );
      sql.execute('ALTER TABLE saved_cards ADD COLUMN currency_code TEXT NULL');
      sql.execute(
        'ALTER TABLE saved_cards ADD COLUMN transaction_count INTEGER NULL',
      );
    }
    if (physical >= 4) {
      sql.execute(
        'ALTER TABLE saved_cards ADD COLUMN session_data_json TEXT NULL',
      );
    }
    if (physical >= 5) {
      sql.execute('''CREATE TABLE card_read_batches (
        id TEXT NOT NULL PRIMARY KEY, card_id TEXT NOT NULL,
        card_fingerprint TEXT NOT NULL, read_at INTEGER NOT NULL,
        parse_version INTEGER NOT NULL DEFAULT 1, payload_json TEXT NOT NULL
      )''');
    }
    _insertLegacyCard(sql, 'legacy-card', payload: payload);
    arrange?.call(sql);
    sql.execute('PRAGMA user_version = $version');
  } finally {
    sql.close();
  }
  return file;
}

void _insertLegacyCard(
  sqlite.Database sql,
  String id, {
  required String payload,
}) {
  final columns = sql
      .select('PRAGMA table_info(saved_cards)')
      .map((r) => r['name'])
      .toSet();
  final values = <String, Object?>{
    'id': id,
    'card_fingerprint': id == 'legacy-card' ? _fingerprint : 'tunion:$id:0001',
    'card_type': CardTypes.chinaTunion,
    'official_name': '旧卡名',
    'custom_name': '通勤卡 001',
    'issuer_name': '旧发行方',
    'city_name': '旧城市',
    'identification_source': CardIdentificationSources.cardCatalog,
    'identification_confidence': .75,
    'card_image_path': 'private/card-001.png',
    'last_read_at': 700,
    'created_at': 100,
    'updated_at': 900,
    if (columns.contains('card_number_masked'))
      'card_number_masked': '****6789',
    if (columns.contains('card_number')) 'card_number': '000123456789',
    if (columns.contains('balance_fen')) 'balance_fen': 0,
    if (columns.contains('currency_code')) 'currency_code': 'HKD',
    if (columns.contains('transaction_count')) 'transaction_count': 0,
    if (columns.contains('session_data_json')) 'session_data_json': payload,
  };
  sql.execute(
    'INSERT INTO saved_cards (${values.keys.join(',')}) '
    'VALUES (${List.filled(values.length, '?').join(',')})',
    values.values.toList(),
  );
}

void _insertBatch(
  sqlite.Database sql,
  String id,
  String cardId,
  String payload,
  int time,
  int parser,
) {
  final fingerprint = sql.select(
    'SELECT card_fingerprint FROM saved_cards WHERE id = ?',
    [cardId],
  ).single['card_fingerprint'];
  sql.execute(
    'INSERT INTO card_read_batches '
    '(id, card_id, card_fingerprint, read_at, parse_version, payload_json) '
    'VALUES (?, ?, ?, ?, ?, ?)',
    [id, cardId, fingerprint, time, parser, payload],
  );
}

