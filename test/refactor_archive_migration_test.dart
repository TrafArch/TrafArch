        () async {
          final (raw, status, parser) = fixture.value;
          final file = _legacyFile(
            5,
            payload: raw,
            arrange: (sql) {
              // A different batch on the same card must not suppress scalar backfill.
              _insertBatch(
                sql,
                'unrelated',
                'legacy-card',
                'other evidence',
                600,
                3,
              );
              // The same raw text on a DIFFERENT card must not suppress it either.
              _insertLegacyCard(sql, 'other-card', payload: raw);
              _insertBatch(sql, 'other-exact', 'other-card', raw, 500, parser);
            },
          );
          String? backfilledId;
          for (var opening = 0; opening < 2; opening++) {
            final db = _database(file);
            try {
              final repo = CardRepository(db);
              await repo.getAllCards(); // Forces actual onUpgrade / beforeOpen.
              await db.transaction(() async {
                await db.backfillLegacySnapshots(cardId: 'legacy-card');
                await db.backfillLegacySnapshots();
              });
              final batches = await repo.watchBatches('legacy-card').first;
              final old = batches.where((b) => b.payloadJson == raw).single;
              expect(old.parseVersion, parser);
              expect(old.readAt, 700);
              expect(old.id, startsWith('legacy-scalar-v6:last_read_at:'));
              if (opening == 0) backfilledId = old.id;
              expect(old.id, backfilledId);
              expect(batches, hasLength(opening == 0 ? 2 : 3));
              final history = await ArchiveHistory(repo).load('legacy-card');
              final evidence = history.batches.singleWhere(
                (b) => b.id == old.id,
              );
              expect(evidence.origin, 'legacy_saved_cards.session_data_json');
              expect(evidence.timeSource, 'last_read_at');
              expect(evidence.decoded.rawJson, raw);
              expect(evidence.decoded.status, status);
              if (evidence.decoded.snapshot case final snapshot?) {
                expect(snapshot.encode(), raw);
              } else {
                expect(evidence.issues, isNotEmpty);
              }
              if (opening == 0) {
                expect(history.latestCapture!.rawJson, raw);
                await repo.saveIdentity(
                  fingerprint: _fingerprint,
                  identity: _unknownIdentity,
                  readAt: _at(1000),
                );
              }
              final saved = await repo.watchCard('legacy-card').first;
              expect(saved!.customName, '通勤卡 001');
              expect(saved.sessionDataJson, isNot(raw));
              expect(
                (await repo.watchBatches('legacy-card').first).where(
                  (b) => b.payloadJson == raw,
                ),
                hasLength(1),
              );
              expect(await repo.watchBatches('other-card').first, hasLength(1));
            } finally {
              await db.close();
            }
          }
        },
      );
    }

